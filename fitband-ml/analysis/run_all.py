"""
run_all.py — every development step, in order (everything except final.py).

    python analysis/run_all.py

1. Sanity checks on windows.csv (window counts, FFT baseline numbers)
2. Stage 1 activity classifier            -> stage1_activity.py
3. Stage 2 heart-rate models + ablations  -> stage2_bpm.py
4. PCA and k-means                        -> unsupervised.py
5. Side experiment (train 1-3, test 4)    -> side_experiment.py
6. Failure analysis of the headline model -> failure_analysis.py
7. Leakage check: no session-5 row was handed out

Tables go to results/tables/, figures to results/figures/, and every number
worth quoting to results/numbers_for_report.md. Only sessions 1-4 are used.
"""

from datetime import datetime

import config
import data
import failure_analysis
import models
import side_experiment
import stage1_activity
import stage2_bpm
import unsupervised


# =============================================================================
#  SANITY CHECKS
# =============================================================================
def check_window_counts(development):
    """Every 5-minute block should give 49-50 six-second windows."""
    counts = development.groupby(["session", "activity"]).size()
    unusual = counts[(counts < 49) | (counts > 50)]
    if len(unusual):
        print(f"WARNING: unusual window counts:\n{unusual}")
    return [("Windows per (session, activity), sessions 1-4",
             f"min {counts.min()}, max {counts.max()}, total {counts.sum()}"
             + ("" if unusual.empty else f"; UNUSUAL: {unusual.to_dict()}"))]


def check_fft_baseline(development):
    """Expected from earlier exploration: about 28 BPM overall, about 2 at rest."""
    constant = development[development["session"].isin(config.CONSTANT_PACE_SESSIONS)]
    overall = models.rmse(constant["fft_bpm"], constant[config.TARGET])
    resting = constant[constant["activity"] == "resting"]
    resting_rmse = models.rmse(resting["fft_bpm"], resting[config.TARGET])
    if not (24 <= overall <= 32 and resting_rmse <= 3):
        print(f"WARNING: FFT baseline differs from the expected ~28 / ~2 BPM: {overall:.2f} / {resting_rmse:.2f}")
    noisy = int(((development[config.TARGET] - development["hr_truth_rr"]).abs() > config.LABEL_NOISE_BPM).sum())
    return [("FFT baseline RMSE, sessions 1-3, all windows", f"{overall:.2f} BPM (expected about 28)"),
            ("FFT baseline RMSE, sessions 1-3, resting", f"{resting_rmse:.2f} BPM (expected about 2)"),
            ("Windows with |hr_truth - hr_truth_rr| > 5 BPM, sessions 1-4", noisy)]


def check_no_leakage():
    """No session-5 rows handed out, and no development script asks for them."""
    assert data.final_rows_returned == 0, "session 5 rows were loaded during development!"
    offenders = [path.name for path in sorted((config.PROJECT_DIR / "analysis").glob("*.py"))
                 if path.name not in ("final.py", "data.py", "run_all.py")
                 and "include_final=True" in path.read_text()]
    assert not offenders, f"these scripts request session 5: {offenders}"
    return [("Leakage check", "passed: 0 session-5 rows loaded; only final.py requests session 5")]


# =============================================================================
#  REPORT FILE
# =============================================================================
def write_numbers(sections):
    lines = ["# Numbers for the report (development data: sessions 1-4)",
             f"\nGenerated by `python analysis/run_all.py` on {datetime.now():%Y-%m-%d %H:%M}. "
             f"Seed {config.SEED}. Headline model: {config.HEADLINE_MODEL}. "
             "Session 5 numbers come only from final.py (results/final/).\n"]
    for title, numbers in sections:
        lines.append(f"\n## {title}\n")
        findings = [value for label, value in numbers if label == "Finding"]
        for label, value in numbers:
            if label != "Finding":
                lines.append(f"- {label}: **{value}**")
        if findings:
            lines.append("\nIn plain words:\n")
            lines += [f"- {sentence}" for sentence in findings]
    config.NUMBERS_FILE.write_text("\n".join(lines) + "\n")


# =============================================================================
#  MAIN
# =============================================================================
def main():
    for folder in (config.TABLES_DIR, config.FIGURES_DIR):
        folder.mkdir(parents=True, exist_ok=True)

    development = data.load_windows()
    sections = [("Sanity checks", check_window_counts(development) + check_fft_baseline(development))]

    steps = [("Stage 1: activity classifier", stage1_activity.main),
             ("Stage 2: heart rate", stage2_bpm.main),
             ("Unsupervised: PCA and k-means", unsupervised.main),
             ("Side experiment: train sessions 1-3, test session 4", side_experiment.main),
             ("Failure analysis (headline model, held-out windows)", failure_analysis.main)]
    for title, step in steps:
        print(f"\n{'=' * 78}\n{title}\n{'=' * 78}")
        sections.append((title, step()))

    sections[0] = ("Sanity checks", sections[0][1] + check_no_leakage())
    write_numbers(sections)
    print(f"\nDone. Tables: {config.TABLES_DIR}\nFigures: {config.FIGURES_DIR}\nNumbers: {config.NUMBERS_FILE}")


if __name__ == "__main__":
    main()
